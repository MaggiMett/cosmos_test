export interface CanonicalAssetImportFixtures {
  png: AssetImportFile;
  webp: AssetImportFile;
  svg: AssetImportFile;
  unsafeSvg: AssetImportFile;
  video: AssetImportFile;
}

/**
 * Returns owned fixture bytes so mutation in one test/import cannot affect
 * another. Fixtures represent media only and contain no catalog metadata.
 */
export function createCanonicalAssetImportFixtures():
Readonly<CanonicalAssetImportFixtures> {
  return Object.freeze({
    png: createFixture("transparent.png", "image/png", TRANSPARENT_PNG_1X1),
    webp: createFixture(
      "transparent.webp",
      "image/webp",
      OPAQUE_WEBP_1X1,
    ),
    svg: createFixture("vector.svg", "image/svg+xml", SAFE_SVG),
    unsafeSvg: createFixture(
      "unsafe.svg",
      "image/svg+xml",
      UNSAFE_SVG,
    ),
    video: createFixture("clip.mp4", "video/mp4", MP4_VIDEO),
  });
}

function createFixture(
  fileName: string,
  declaredMimeType: string,
  bytes: Uint8Array,
): AssetImportFile {
  return {
    fileName,
    declaredMimeType,
    bytes: bytes.slice(),
  };
}
